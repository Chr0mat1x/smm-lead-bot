"""Разовый прогрев кеша координат городов.

Зачем: Nominatim режет облачные IP и лимитирует 1 запрос/сек, поэтому на
хостинге геокодинг может не работать вовсе. Кеш лежит в smm_bot/geo_cache
и едет в образ, так что поиск по этим городам работает без сети.

Запуск (локально, где Nominatim доступен):

    python scripts/prewarm_geo.py

Скрипт идемпотентный: уже прогретые города не переспрашивает, а испорченные
записи (рамка нулевой площади) перезаписывает.
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from smm_bot import osm  # noqa: E402

CITIES = [
    "Москва", "Санкт-Петербург", "Новосибирск", "Екатеринбург", "Казань",
    "Нижний Новгород", "Челябинск", "Самара", "Омск", "Ростов-на-Дону",
    "Уфа", "Красноярск", "Воронеж", "Пермь", "Волгоград", "Краснодар",
    "Саратов", "Тюмень", "Тольятти", "Ижевск", "Барнаул", "Ульяновск",
    "Иркутск", "Хабаровск", "Ярославль", "Владивосток", "Махачкала",
    "Томск", "Оренбург", "Кемерово", "Новокузнецк", "Рязань", "Астрахань",
    "Набережные Челны", "Пенза", "Липецк", "Киров", "Чебоксары", "Тула",
    "Калининград", "Балашиха", "Курск", "Севастополь", "Сочи", "Ставрополь",
    "Улан-Удэ", "Тверь", "Магнитогорск", "Иваново", "Брянск", "Белгород",
    "Сургут", "Владимир", "Нижний Тагил", "Архангельск", "Чита", "Калуга",
    "Смоленск", "Волжский", "Якутск", "Саранск", "Череповец", "Курган",
    "Орёл", "Подольск", "Грозный", "Люберцы", "Мурманск", "Тамбов",
    "Петрозаводск", "Стерлитамак", "Вологда", "Ярославль", "Нальчик",
    "Миасс", "Тобольск", "Ноябрьск", "Новый Уренгой", "Кисловодск",
    "Пятигорск", "Геленджик", "Анапа", "Новороссийск", "Таганрог",
    "Шахты", "Дзержинск", "Первоуральск", "Каменск-Уральский",
]


def main() -> int:
    ok = failed = 0
    for city in dict.fromkeys(CITIES):  # без дублей, порядок сохраняем
        try:
            area = osm.geocode(city)
        except Exception as exc:  # noqa: BLE001 — прогреваем всё, что получится
            print(f"  {city}: ОШИБКА {str(exc)[:70]}")
            failed += 1
        else:
            print(f"  {city}: {area.name!r} bbox={tuple(round(x, 2) for x in area.bbox)}")
            ok += 1
        time.sleep(1.1)  # уважаем лимит Nominatim 1 запрос/сек

    print(f"\nГотово: ok={ok} fail={failed}")
    print(f"Файлов в кеше: {len(list(osm.GEO_CACHE_DIR.glob('geo_*.json')))}")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
